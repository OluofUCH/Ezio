import { execFile } from 'node:child_process'
import { networkInterfaces } from 'node:os'
import { promisify } from 'node:util'

const execFileAsync = promisify(execFile)

export function lanAddresses(): string[] {
  const addresses: string[] = []
  for (const entries of Object.values(networkInterfaces())) {
    for (const entry of entries ?? []) {
      if (entry.family === 'IPv4' && !entry.internal) addresses.push(entry.address)
    }
  }
  return addresses
}

export function studentUrl(port: number): string {
  const [address] = lanAddresses()
  return address ? `http://${address}:${port}` : `http://localhost:${port}`
}

/**
 * Check whether the installer's firewall rule is present. Advisory only: the
 * wizard shows it so an invigilator can fix a blocked port before thirty students
 * are staring at a connection error. On non-Windows hosts this returns null.
 */
export async function firewallRulePresent(): Promise<boolean | null> {
  if (process.platform !== 'win32') return null

  try {
    await execFileAsync('netsh', [
      'advfirewall',
      'firewall',
      'show',
      'rule',
      'name=CBT Hall Server',
    ])
    return true
  } catch {
    return false
  }
}

/**
 * Back up the SQLite database with `VACUUM INTO`, which produces a consistent
 * single file even while the server is serving requests. The destination is
 * always inside the data directory and is generated by this process.
 */
export function backupFileName(now = new Date()): string {
  const stamp = now.toISOString().replace(/[:.]/g, '-').replace('T', '_').replace('Z', '')
  return `cbt-hall-${stamp}.db`
}
