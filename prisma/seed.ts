/**
 * DATABASE SEED
 * =============
 *
 * Two separable jobs:
 *
 *   1. The platform bootstrap — a SUPER_ADMIN. Without one, nobody can create the
 *      first school, and no other account can be created without a school. This runs
 *      in every environment, production included.
 *
 *   2. A demo school with staff, a roster and a published exam, so the API can be
 *      exercised end-to-end (and `npm run smoke` has something to log into). Skipped
 *      in production — seeding fictional students into a real school's database is
 *      not a mistake worth leaving one env var away from happening.
 *
 * Idempotent throughout: every write is an upsert or guarded by an existence check, so
 * re-running after a schema change tops the data up instead of duplicating it.
 *
 * One of the three legitimate uses of `unscopedDb` (see lib/db.ts) — this runs outside
 * any request, so there is no session to derive a tenant scope from.
 */

