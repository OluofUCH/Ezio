function env(name: string, fallback: string): string {
  const value = process.env[name]
  return value && value.trim() ? value.trim() : fallback
}

async function seedSuperAdmin(): Promise<void> {
  const email = env('SEED_SUPER_ADMIN_EMAIL', 'superadmin@cbt.local').toLowerCase()
  const password = env('SEED_SUPER_ADMIN_PASSWORD', 'ChangeMe123!')

  if (process.env.NODE_ENV === 'production') {
    const explicit = process.env.SEED_SUPER_ADMIN_PASSWORD?.trim() ?? ''
    if (!explicit || explicit.length < 12 || explicit === 'ChangeMe123!') {
      throw new Error(
        'Refusing to seed a production SUPER_ADMIN without SEED_SUPER_ADMIN_PASSWORD set to a unique password of at least 12 characters.',
      )
    }
  }

  /**
   * `update: {}` — an existing super admin is left completely alone. Re-running the
   * seed must never reset a password that has since been changed, which is exactly
   * what an `update: { passwordHash }` here would do on every deploy.
   */
  const admin = await unscopedDb.user.upsert({
    where: { email },
    update: {},
    create: {
      email,
      passwordHash: await hashPassword(password),
      fullName: 'Platform Super Admin',
      role: 'SUPER_ADMIN',
      // Null by design: a SUPER_ADMIN sits above every tenant and selects a school
      // per-request with ?schoolId= (lib/auth/session.ts).
      schoolId: null,
    },
    select: { id: true, email: true, createdAt: true, updatedAt: true },
  })

  const isNew = admin.createdAt.getTime() === admin.updatedAt.getTime()
  console.log(`  ${isNew ? 'created' : 'exists '}  SUPER_ADMIN  ${admin.email}`)
  if (isNew) console.log(`             password: ${password}  <-- change this after first login`)
}

async function seedDemoSchool(): Promise<void> {
  const school = await unscopedDb.school.upsert({
    where: { slug: DEMO_SLUG },
    update: {},
    create: {
      name: 'Demo Academy',
      slug: DEMO_SLUG,
      address: '12 Awolowo Road, Ikoyi, Lagos',
      isActive: true,
    },
    select: { id: true, name: true, slug: true },
  })
  console.log(`  school       ${school.name} (${school.slug})`)

  const password = env('SEED_DEMO_PASSWORD', 'DemoPassword123!')
  const passwordHash = await hashPassword(password)

  const [schoolAdmin, teacher] = await Promise.all([
    unscopedDb.user.upsert({
      where: { email: 'admin@demo-academy.local' },
      update: {},
      create: {
        email: 'admin@demo-academy.local',
        passwordHash,
        fullName: 'Grace Oluwaseun Adeyemi',
        role: 'SCHOOL_ADMIN',
        schoolId: school.id,
      },
      select: { id: true, email: true },
    }),
    unscopedDb.user.upsert({
      where: { email: 'teacher@demo-academy.local' },
      update: {},
      create: {
        email: 'teacher@demo-academy.local',
        passwordHash,
        fullName: 'Ibrahim Musa Yusuf',
        role: 'TEACHER',
        schoolId: school.id,
      },
      select: { id: true, email: true },
    }),
  ])
  console.log(`  admin        ${schoolAdmin.email}`)
  console.log(`  teacher      ${teacher.email}`)
  console.log(`  password     ${password}  (both staff accounts)`)

  for (const student of DEMO_STUDENTS) {
    await unscopedDb.student.upsert({
      where: { schoolId_regNumber: { schoolId: school.id, regNumber: student.regNumber } },
      update: {},
      create: { ...student, schoolId: school.id },
    })
  }
  console.log(`  students     ${DEMO_STUDENTS.length} (JSS2 x3, SS1 x1)`)

  /**
   * A provisioned exam hall, so the offline path can be exercised without a manual
   * provisioning round trip (`npm run smoke-sync`, and the local-server's own setup).
   *
   * The key is FIXED and comes from the environment, which is the exact opposite of how a
   * real key is issued — `POST /api/local-servers` mints 32 CSPRNG bytes and shows them
   * once. A predictable key is acceptable only because this whole function is skipped when
   * NODE_ENV=production, and it is what lets a dev pull an exam onto a test device without
   * copying a secret out of an API response by hand.
   */
  const demoDeviceKey = env('SEED_DEMO_DEVICE_KEY', 'cbt_dev_seeddemokey0000000000000000000000000')
  const demoKeyHash = hashDeviceKey(demoDeviceKey)

  const localServer = await unscopedDb.localServer.upsert({
    // Unique on the digest, so re-running with the same key updates rather than duplicating.
    where: { deviceKey: demoKeyHash },
    update: {},
    create: {
      schoolId: school.id,
      name: 'Exam Hall A - Server',
      deviceKey: demoKeyHash,
      deviceKeyPrefix: demoDeviceKey.slice(0, 'cbt_dev_'.length + 8),
    },
    select: { id: true, name: true, deviceKeyPrefix: true },
  })
  console.log(`  localServer  ${localServer.name} (${localServer.deviceKeyPrefix}…)`)

  /**
   * Existence-checked rather than upserted. An exam that already has sessions has a
   * frozen question set (`resolveEditableExam` in lib/tenant.ts), and re-seeding
   * questions underneath a graded sitting would invalidate its `maxScore` snapshot.
   * Leaving it alone is the only safe re-run.
   */
  const existing = await unscopedDb.exam.findFirst({
    where: { schoolId: school.id, title: 'JSS2 General Knowledge — First Term' },
    select: { id: true },
  })

  if (existing) {
    console.log('  exam         already seeded, left untouched')
    return
  }

  const exam = await unscopedDb.exam.create({
    data: {
      schoolId: school.id,
      title: 'JSS2 General Knowledge — First Term',
      subject: 'General Knowledge',
      classLevel: ClassLevel.JSS2,
      durationMins: 30,
      mode: 'HYBRID',
      shuffleQuestions: true,
      shuffleOptions: true,
      maxAttempts: 1,
      // No start/end window: available immediately, so the smoke test can sit it
      // without depending on the wall clock.
      startWindow: null,
      endWindow: null,
      isPublished: true,
      createdById: teacher.id,
      questions: {
        create: DEMO_QUESTIONS.map((question, index) => ({
          text: question.text,
          type: question.type,
          points: question.points,
          orderIndex: index,
          options: {
            create: question.options.map((option, optionIndex) => ({
              text: option.text,
              isCorrect: option.isCorrect,
              orderIndex: optionIndex,
            })),
          },
        })),
      },
    },
    select: { id: true, title: true, _count: { select: { questions: true } } },
  })

  const totalPoints = DEMO_QUESTIONS.reduce((sum, question) => sum + question.points, 0)
  console.log(`  exam         "${exam.title}" — ${exam._count.questions} questions, ${totalPoints} points, published`)
}

async function main(): Promise<void> {
  console.log('\nSeeding CBT platform\n')

  await seedSuperAdmin()

  if (process.env.NODE_ENV === 'production') {
    console.log('\n  NODE_ENV=production — demo school skipped.\n')
    return
  }

  console.log('\nDemo school\n')
  await seedDemoSchool()

  console.log('\nStudent exam logins (schoolSlug + regNumber + pin):')
  for (const student of DEMO_STUDENTS) {
    console.log(`  ${DEMO_SLUG}  ${student.regNumber}  ${student.pin}  ${student.classLevel}  ${student.fullName}`)
  }

  console.log('\nOffline exam hall (local-server/.env):')
  console.log(`  CLOUD_DEVICE_KEY="${env('SEED_DEMO_DEVICE_KEY', 'cbt_dev_seeddemokey0000000000000000000000000')}"`)
  console.log('  CLOUD_BASE_URL="http://localhost:3000"')
  console.log('')
}

main()
  .catch((error) => {
    console.error('\nSeed failed:', error)
    // Non-zero exit so a CI step or `prisma migrate dev` reports the failure instead
    // of continuing against a half-seeded database.
    process.exitCode = 1
  })
  .finally(async () => {
    await unscopedDb.$disconnect()
  })
